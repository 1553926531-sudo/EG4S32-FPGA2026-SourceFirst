
from cli_zh import EnglishArgumentParser, run
import json
import math
from pathlib import Path
from tfm_format import parse_header

ROOT = Path(__file__).resolve().parents[1]


class ReadOnlySectors:
    def __init__(self, stream):
        self.stream = stream

    def read_sector(self, lba):
        if lba < 0:
            raise ValueError("Sector address must be nonnegative")
        self.stream.seek(lba * 512)
        b = self.stream.read(512)
        if len(b) != 512:
            raise ValueError(f"Incomplete read of physical sector {lba}")
        return b

    def write_sector(self, *args, **kwargs):
        raise PermissionError("Read-only backend; writes are disabled")


def coalesce(lbas):
    extents = []
    for logical, physical in enumerate(lbas):
        if not 0 <= physical < 2**32:
            raise ValueError("Physical sector address exceeds the 32-bit SDHC/SDXC range")
        if extents and physical == extents[-1][1] + extents[-1][2]:
            a, b, count = extents[-1]
            extents[-1] = (a, b, count + 1)
        else:
            extents.append((logical, physical, 1))
    if not extents or len(extents) > 64:
        raise ValueError("File must occupy 1-64 contiguous extents; save a new copy and export again")
    return extents


def emit_rom(extents, sectors, crc, output):
    lines = ["// Generated by read-only export_map.py. Valid only for this exact file allocation.",
             "module media_extent_map(input wire [31:0] logical_lba, output reg [31:0] physical_lba,",
             " output reg valid, output wire [31:0] expected_header_crc, output wire [31:0] file_sectors);",
             f"assign expected_header_crc = 32'h{crc:08x};", f"assign file_sectors = 32'd{sectors};",
             "always @* begin physical_lba = 0; valid = 0;"]
    for logical, physical, count in extents:
        lines += [f" if (logical_lba >= 32'd{logical} && logical_lba < 32'd{logical + count}) begin",
                  f"  physical_lba = 32'd{physical} + (logical_lba - 32'd{logical}); valid = 1; end"]
    lines += ["end", "endmodule", ""]
                                                                    
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8")


def export(link, name, out, physical_offset_sectors=0):
    from reference_exfat import ExfatVolume
    volume = ExfatVolume(link)
    entry = volume.find(name)
    if entry is None:
        raise FileNotFoundError(f"File not found in exFAT root: {name}")
    if entry["attributes"] & 0x10:
        raise IsADirectoryError(name)
    if entry["length"] != entry["valid_length"] or entry["length"] % 512:
        raise ValueError("Media file must be fully initialized and sector aligned (512 bytes)")
    clusters = volume.file_clusters(entry)
    sectors = entry["length"] // 512
    lbas = [volume.cluster_lba(c) + s for c in clusters for s in range(volume.spc)][:sectors]
    if len(lbas) != sectors or len(set(lbas)) != sectors:
        raise ValueError("Incomplete or overlapping file cluster chain")
    header = parse_header(link.read_sector(lbas[0]))
    if header["sectors"] != sectors:
        raise ValueError("Directory length differs from media container length")
    if not isinstance(physical_offset_sectors, int) or physical_offset_sectors < 0:
        raise ValueError('Partition offset must be a nonnegative integer sector count')
    extents = coalesce([lba + physical_offset_sectors for lba in lbas])
    emit_rom(extents, sectors, header["header_crc"], out)
    report = dict(file=name, sectors=sectors, header=header, extents=extents,
                  physical_offset_sectors=physical_offset_sectors,
                  note="Read-only metadata export; no sector writes, formatting, or FPGA programming.")
    out.with_suffix(".json").write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
    return report


def main():
    p = EnglishArgumentParser(description='Read exFAT metadata and export up to 64 file extents. Never writes card sectors.')
    source = p.add_mutually_exclusive_group(required=True)
    source.add_argument("--image", help="Disk image or Windows device path opened read-only")
    source.add_argument("--port", help="Legacy v29 sector-reader firmware only; use before loading the new player")
    p.add_argument("--baud", type=int, default=1000000, help="Legacy firmware baud rate (default: 1000000)")
    p.add_argument("--name", default="DEMO.PAK", help="Exact filename in the exFAT root directory")
    p.add_argument('--volume-offset-sectors', type=int, default=0,
                   help='Whole-card start sector for a partition-volume input; use 0 for a whole-disk image')
    p.add_argument("--out", type=Path, default=ROOT / "rtl/media_extent_map.v", help="Local map Verilog output, with matching JSON")
    a = p.parse_args()
    if a.port and a.volume_offset_sectors:
        p.error('Serial access addresses the whole card; a partition offset is not allowed')
    if a.port:
        import serial
        from reference_sector_io import SectorLink
        with serial.Serial(a.port, a.baud, timeout=0.1, dsrdtr=False, rtscts=False) as port:
            link = SectorLink(port)
                                                                        
            report = export(link, a.name, a.out)
    else:
        with open(a.image, "rb", buffering=0) as f:
            report = export(ReadOnlySectors(f), a.name, a.out, a.volume_offset_sectors)
    print('Read-only map export complete. Re-export and rebuild if file allocation changes.')
    print(json.dumps(report, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    run(main)
